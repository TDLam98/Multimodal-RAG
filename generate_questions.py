"""
Generate lookup questions automatically from the parsed financial statements.

Run (from the project folder, after parse_html.py):
    python generate_questions.py
    python generate_questions.py --per-filing 5     # eval questions per real-PDF filing (default 5)

How it works
  It reads the HTML table chunks (data/chunks/html/*.jsonl), finds the main financial statements
  (balance sheet, income statement, cash flow statement), and looks for standard line items such
  as Total assets or Net cash provided by operating activities. The answer is copied exactly as
  printed in the filing, from the column for the filing's own fiscal year.

Outputs
  questions_eval_draft.csv   (project folder) About 5 questions per filing that has a real PDF in
                             data/real_pdf/. CHECK EVERY ROW against the PDF, fill in the
                             "verified" column with y or n, and save it as questions.csv. This is
                             your evaluation set; commit it to Git.
  data/questions_train.csv   Questions from every OTHER company, for training the reranker in
                             Phase 3. Splitting by company keeps training and test data apart.
                             It is regenerated from your data, so it is not committed.

Limitations (say so in the report)
  - Every generated question is a table lookup. Text questions and questions that need both a
    table and the text must be written by hand; add them to questions.csv with label "text" or
    "both".
  - Picking the column relies on finding a row of years above the numbers. When none is found,
    the first number in the row is used and the row is marked confidence=low. Check those first.
  - Numbers are as printed, usually in millions. The "units" column records what the table says.

Requires: nothing beyond the project's existing packages.
"""
import argparse
import csv
import json
import random
import re
from datetime import date
from pathlib import Path

from ingest import DATA_DIR, sec_get

PROJECT_DIR = Path(__file__).resolve().parent
EVAL_OUT = PROJECT_DIR / "questions_eval_draft.csv"
TRAIN_OUT = DATA_DIR / "questions_train.csv"
NAMES_CACHE = DATA_DIR / "company_names.json"
REAL_PDF_DIR = DATA_DIR / "real_pdf"
SEED = 42

# statement -> keywords that identify it in a table's title
STATEMENTS = {
    "balance": ["balance sheet", "financial position", "financial condition"],
    "income": ["statements of operations", "statement of operations", "statements of income",
               "statement of income", "statements of earnings", "statement of earnings",
               "income statement"],
    "cashflow": ["cash flows", "cash flow"],
}

# (metric id, statement, label regex, phrase used in the question, point-in-time?)
METRICS = [
    ("total_assets", "balance", r"total assets", "total assets", True),
    ("total_liabilities", "balance", r"total liabilities", "total liabilities", True),
    ("current_assets", "balance", r"total current assets", "total current assets", True),
    ("current_liabilities", "balance", r"total current liabilities", "total current liabilities", True),
    ("cash", "balance", r"cash and cash equivalents", "cash and cash equivalents", True),
    ("equity", "balance",
     r"total (stockholders|shareholders|shareowners|share owners)(’|')? equity",
     "total stockholders' equity", True),
    ("revenue", "income", r"(total )?(net )?(revenues?|sales|net sales)", "total revenue (net sales)", False),
    ("operating_income", "income", r"(total )?(operating income|income from operations)",
     "operating income", False),
    ("net_income", "income", r"net (income|earnings)", "net income", False),
    ("operating_cash_flow", "cashflow",
     r"(net )?cash (provided by|from|generated by|generated from) operating activities",
     "net cash provided by operating activities", False),
    ("capex", "cashflow",
     r"(capital expenditures|purchases of property,? (plant )?(and|&) equipment|"
     r"payments for (acquisition of )?property,? plant(,)? and equipment)",
     "capital expenditures", False),
]

NUM_RE = re.compile(r"^\(?-?\d[\d,]*(\.\d+)?\)?$")
YEAR_RE = re.compile(r"\b(19|20)\d{2}\b")


# ---------- company names ----------
def company_names():
    """Ticker -> company name from SEC's ticker table, cached in data/company_names.json."""
    if NAMES_CACHE.exists():
        return json.loads(NAMES_CACHE.read_text(encoding="utf-8"))
    try:
        data = sec_get("https://www.sec.gov/files/company_tickers.json").json()
        names = {}
        for row in data.values():
            title = row["title"].strip()
            if title.isupper():                      # "EXXON MOBIL CORP" -> "Exxon Mobil Corp"
                title = title.title()
            names[row["ticker"].upper()] = title
        NAMES_CACHE.write_text(json.dumps(names, indent=1), encoding="utf-8")
        return names
    except Exception as e:
        print(f"Could not fetch company names ({e}); using tickers instead.")
        return {}


# ---------- table helpers ----------
def table_rows(chunk):
    """Rows of a serialized table chunk, skipping its TABLE: title line."""
    lines = chunk["text"].splitlines()
    if lines and lines[0].startswith("TABLE:"):
        lines = lines[1:]
    return [[c.strip() for c in line.split(" | ")] for line in lines]


def statement_of(chunk):
    text = (chunk.get("title", "") + " " + chunk["text"][:300]).lower()
    for stmt, keys in STATEMENTS.items():
        if any(k in text for k in keys):
            return stmt
    return None


def year_header(rows):
    """Years in column order, from the first row whose cells all contain one year."""
    for row in rows[:6]:
        cells = [c for c in row if c]
        years = [YEAR_RE.search(c) for c in cells]
        if len(cells) >= 2 and all(years):
            return [int(m.group(0)) for m in years]
    return None


def normalize_label(s):
    s = s.lower().replace("’", "'").strip()
    s = re.sub(r"\(\w\)$|\*+$|:$", "", s).strip()   # trailing footnote markers and colons
    return re.sub(r"\s+", " ", s)


def units_of(chunk):
    t = (chunk.get("title", "") + " " + chunk["text"][:300]).lower()
    for u in ("billions", "millions", "thousands"):
        if f"in {u}" in t:
            return u
    return ""


def pick_value(values, years, fiscal_year):
    """The value for the filing's own fiscal year, and how confident that choice is."""
    nums = [v for v in values if NUM_RE.match(v)]
    if not nums:
        return None, None
    if years and len(nums) == len(years):
        for target in (fiscal_year, fiscal_year - 1):     # -1: years ending in early January
            if target in years:
                return nums[years.index(target)], "high"
        return None, None
    return nums[0], "low"


# ---------- generation ----------
def fiscal_year_of(report_date):
    d = date.fromisoformat(report_date)
    return d.year


def nice_date(report_date):
    d = date.fromisoformat(report_date)
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def make_question(name, phrase, point_in_time, report_date):
    when = nice_date(report_date)
    verb = "were" if phrase.endswith(("assets", "liabilities", "equivalents", "expenditures")) else "was"
    if point_in_time:
        return f"What {verb} {name}'s {phrase} as of {when}, as reported in its Form 10-K?"
    return f"What {verb} {name}'s {phrase} for the fiscal year ended {when}, as reported in its Form 10-K?"


def questions_for_filing(path, names):
    chunks = [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]
    tables = [c for c in chunks if c["source"] == "html_table"]
    found = {}
    for c in tables:
        stmt = statement_of(c)
        if not stmt:
            continue
        rows = table_rows(c)
        years = year_header(rows)
        fy = fiscal_year_of(c["report_date"])
        for metric, mstmt, pattern, phrase, pit in METRICS:
            if mstmt != stmt or metric in found:
                continue                       # first matching statement table wins
            for row in rows:
                if len(row) < 2 or not re.fullmatch(pattern, normalize_label(row[0])):
                    continue
                value, confidence = pick_value(row[1:], years, fy)
                if value is None:
                    continue
                name = names.get(c["ticker"], c["ticker"])
                found[metric] = {
                    "filing": c["filing"], "ticker": c["ticker"], "metric": metric,
                    "question": make_question(name, phrase, pit, c["report_date"]),
                    "answer": value, "row_label": row[0], "label": "table",
                    "statement": stmt, "units": units_of(c), "confidence": confidence,
                    "source_chunk": c["chunk_id"],
                }
                break
    return list(found.values())


def pick_eval(qs, n, rng):
    """Up to n questions, spread across the three statements, high-confidence first."""
    qs = sorted(qs, key=lambda q: (q["confidence"] != "high", rng.random()))
    chosen, by_stmt = [], {}
    for q in qs:
        by_stmt.setdefault(q["statement"], []).append(q)
    while len(chosen) < n and any(by_stmt.values()):
        for stmt in ("balance", "income", "cashflow"):
            if by_stmt.get(stmt) and len(chosen) < n:
                chosen.append(by_stmt[stmt].pop(0))
    return chosen


def write_rows(path, rows, extra=()):
    fields = ["id", "filing", "question", "answer", "row_label", "label", *extra,
              "statement", "units", "confidence", "metric", "source_chunk"]
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def main(per_filing):
    chunk_dir = DATA_DIR / "chunks" / "html"
    files = sorted(chunk_dir.glob("*.jsonl"))
    if not files:
        raise SystemExit(f"No chunk files in {chunk_dir}. Run parse_html.py first.")
    real = {p.stem for p in REAL_PDF_DIR.glob("*.pdf")} if REAL_PDF_DIR.exists() else set()
    real_tickers = {s.partition("_")[0] for s in real}
    if not real:
        print(f"No PDFs found in {REAL_PDF_DIR}; every question goes to the training file.")

    names = company_names()
    rng = random.Random(SEED)
    eval_rows, train_rows, no_questions, unmatched = [], [], [], set(real)

    for path in files:
        qs = questions_for_filing(path, names)
        if not qs:
            no_questions.append(path.stem)
            continue
        if path.stem in real:
            unmatched.discard(path.stem)
            eval_rows += pick_eval(qs, per_filing, rng)
        elif qs[0]["ticker"] not in real_tickers:
            train_rows += qs
        # other filings of real-PDF companies go to neither file, so no company is in both splits

    for i, q in enumerate(eval_rows, 1):
        q["id"], q["verified"] = f"q{i:03d}", ""
    for i, q in enumerate(train_rows, 1):
        q["id"] = f"t{i:04d}"
    write_rows(EVAL_OUT, eval_rows, extra=("verified",))
    write_rows(TRAIN_OUT, train_rows)

    low = sum(1 for q in eval_rows if q["confidence"] == "low")
    print(f"Eval draft: {len(eval_rows)} questions from {len(real) - len(unmatched)} real-PDF filings "
          f"-> {EVAL_OUT.name} ({low} marked confidence=low; check those first)")
    print(f"Training:   {len(train_rows)} questions -> {TRAIN_OUT}")
    if unmatched:
        print(f"Real PDFs with no matching HTML chunk file (check the names): {sorted(unmatched)}")
    if no_questions:
        print(f"{len(no_questions)} filings gave no questions, e.g. {no_questions[:5]}. "
              "Their statements may be in an exhibit, or titled unusually.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Generate lookup questions from parsed financial statements.")
    ap.add_argument("--per-filing", type=int, default=5, help="eval questions per real-PDF filing")
    args = ap.parse_args()
    main(args.per_filing)